#include <stdio.h>

int main() {
    int edad;

    // Pedir al usuario que ingrese su edad
    printf("Por favor, ingresa tu edad: ");
    scanf("%d", &edad);

    // Validar si la entrada es un número negativo
    if (edad < 0) {
        printf("Error: La edad no puede ser un número negativo.\n");
    } 
    // Validar la mayoría de edad (18 años o más)
    else if (edad >= 18) {
        printf("Eres mayor de edad.\n");
    } 
    // Si es menor de 18 y no es negativo
    else {
        printf("Eres menor de edad.\n");
    }

    return 0;
}

